-- V8 (W4·D1): payment attempts for a booking.
--
-- One booking can have several attempts (a retry after a failed payment), numbered 1, 2, 3 ...
-- but at most ONE attempt may be open (CREATED) or successful (CAPTURED) at a time:
-- ux_payments_live_booking enforces that in the database, whatever the app code does.
--
-- gateway + gateway_order_id identify the order at the provider (Razorpay "order_...", mock "order_mock_...").
-- Webhooks (W4·D3) look payments up by it, so it is unique per gateway.
-- amount_paise is computed on the server from the booking; the client never sends an amount.

CREATE TABLE payments (
    id                  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id          bigint       NOT NULL CONSTRAINT fk_payments_booking REFERENCES bookings (id),
    attempt             int          NOT NULL,
    gateway             varchar(16)  NOT NULL,
    gateway_order_id    varchar(64)  NOT NULL,
    gateway_payment_id  varchar(64),
    amount_paise        bigint       NOT NULL,
    currency            char(3)      NOT NULL DEFAULT 'INR',
    status              varchar(16)  NOT NULL DEFAULT 'CREATED',
    failure_reason      varchar(255),
    captured_at         timestamptz,
    failed_at           timestamptz,
    refunded_at         timestamptz,
    version             bigint       NOT NULL DEFAULT 0,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_payments_booking_attempt UNIQUE (booking_id, attempt),
    CONSTRAINT uq_payments_gateway_order   UNIQUE (gateway, gateway_order_id),
    CONSTRAINT ck_payments_attempt   CHECK (attempt >= 1),
    CONSTRAINT ck_payments_gateway   CHECK (gateway IN ('MOCK', 'RAZORPAY')),
    CONSTRAINT ck_payments_amount    CHECK (amount_paise > 0),
    CONSTRAINT ck_payments_status    CHECK (status IN ('CREATED', 'CAPTURED', 'FAILED', 'REFUNDED')),
    CONSTRAINT ck_payments_captured  CHECK (status NOT IN ('CAPTURED', 'REFUNDED')
                                            OR (gateway_payment_id IS NOT NULL AND captured_at IS NOT NULL)),
    CONSTRAINT ck_payments_failed    CHECK (status <> 'FAILED' OR failed_at IS NOT NULL),
    CONSTRAINT ck_payments_refunded  CHECK (status <> 'REFUNDED' OR refunded_at IS NOT NULL)
);

-- At most one open or successful payment per booking (FAILED / REFUNDED rows are history).
CREATE UNIQUE INDEX ux_payments_live_booking ON payments (booking_id) WHERE status IN ('CREATED', 'CAPTURED');
