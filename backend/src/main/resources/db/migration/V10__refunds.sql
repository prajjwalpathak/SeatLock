-- V10 (W4·D4): refunds, written as an OUTBOX.
--
-- A refund row is inserted in the same transaction as the decision that needs it (a late payment captured after
-- the booking expired, a second payment for the same order, a cancellation). A worker then calls the provider
-- OUTSIDE any transaction and records the result. So a refund is never forgotten (the row exists or the decision
-- rolled back) and never sent twice:
--   * one refund per provider payment and reason (uq_refunds_payment_reason)
--   * receipt = our idempotency key at the provider; before (re)trying, the worker looks the receipt up there
--
-- status PENDING: not yet accepted by the provider (retried with backoff: attempts, next_attempt_at)
-- status SUBMITTED: accepted (gateway_refund_id set); the provider pays it out
-- status FAILED: gave up after max attempts; needs a human (last_error)

CREATE TABLE refunds (
    id                  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id          bigint       NOT NULL CONSTRAINT fk_refunds_payment REFERENCES payments (id),
    gateway_payment_id  varchar(64)  NOT NULL,
    amount_paise        bigint       NOT NULL,
    reason              varchar(24)  NOT NULL,
    status              varchar(16)  NOT NULL DEFAULT 'PENDING',
    receipt             varchar(40)  NOT NULL,
    gateway_refund_id   varchar(64),
    attempts            int          NOT NULL DEFAULT 0,
    next_attempt_at     timestamptz  NOT NULL,
    last_error          varchar(255),
    submitted_at        timestamptz,
    version             bigint       NOT NULL DEFAULT 0,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_refunds_receipt          UNIQUE (receipt),
    CONSTRAINT uq_refunds_gateway_refund   UNIQUE (gateway_refund_id),
    CONSTRAINT uq_refunds_payment_reason   UNIQUE (gateway_payment_id, reason),
    CONSTRAINT ck_refunds_amount    CHECK (amount_paise > 0),
    CONSTRAINT ck_refunds_reason    CHECK (reason IN ('LATE_PAYMENT', 'DUPLICATE_PAYMENT', 'CANCELLATION')),
    CONSTRAINT ck_refunds_status    CHECK (status IN ('PENDING', 'SUBMITTED', 'FAILED')),
    CONSTRAINT ck_refunds_submitted CHECK (status <> 'SUBMITTED' OR (gateway_refund_id IS NOT NULL AND submitted_at IS NOT NULL)),
    CONSTRAINT ck_refunds_attempts  CHECK (attempts >= 0)
);

-- The worker's query: due PENDING refunds, oldest first.
CREATE INDEX ix_refunds_due ON refunds (next_attempt_at) WHERE status = 'PENDING';
