-- V1__init.sql: core schema (identity, catalog, booking). See docs/architecture.md.
-- Conventions: bigint identity PKs, timestamptz (UTC), money in paise (bigint),
-- enums as varchar + CHECK, explicitly named constraints.

-- =========================== identity ===========================
CREATE TABLE users (
                       id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email          varchar(254) NOT NULL,
                       password_hash  varchar(100),
                       display_name   varchar(100) NOT NULL,
                       role           varchar(20)  NOT NULL DEFAULT 'USER',
                       auth_provider  varchar(20)  NOT NULL DEFAULT 'LOCAL',
                       created_at     timestamptz  NOT NULL DEFAULT now(),
                       updated_at     timestamptz  NOT NULL DEFAULT now(),
                       CONSTRAINT uq_users_email            UNIQUE (email),
                       CONSTRAINT ck_users_email_lowercase  CHECK (email = lower(email)),
                       CONSTRAINT ck_users_role             CHECK (role IN ('USER', 'ORGANIZER', 'ADMIN')),
                       CONSTRAINT ck_users_auth_provider    CHECK (auth_provider IN ('LOCAL', 'GOOGLE')),
                       CONSTRAINT ck_users_local_password   CHECK (auth_provider <> 'LOCAL' OR password_hash IS NOT NULL)
);

-- =========================== catalog ===========================
CREATE TABLE venues (
                        id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name        varchar(150) NOT NULL,
                        city        varchar(80)  NOT NULL,
                        address     varchar(300) NOT NULL,
                        created_at  timestamptz  NOT NULL DEFAULT now(),
                        updated_at  timestamptz  NOT NULL DEFAULT now(),
                        CONSTRAINT uq_venues_name_city UNIQUE (name, city)
);

CREATE TABLE seats (
                       id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       venue_id     bigint      NOT NULL CONSTRAINT fk_seats_venue REFERENCES venues (id),
                       section      varchar(40) NOT NULL,
                       row_label    varchar(5)  NOT NULL,
                       seat_number  int         NOT NULL,
                       grid_row     int         NOT NULL,
                       grid_col     int         NOT NULL,
                       is_aisle     boolean     NOT NULL DEFAULT false,
                       CONSTRAINT uq_seats_label        UNIQUE (venue_id, section, row_label, seat_number),
                       CONSTRAINT uq_seats_grid         UNIQUE (venue_id, grid_row, grid_col),
                       CONSTRAINT ck_seats_number       CHECK (seat_number > 0),
                       CONSTRAINT ck_seats_grid         CHECK (grid_row >= 0 AND grid_col >= 0)
);
-- (venue_id lookups are covered by uq_seats_label, which starts with venue_id)

CREATE TABLE events (
                        id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        organizer_id      bigint       NOT NULL CONSTRAINT fk_events_organizer REFERENCES users (id),
                        title             varchar(200) NOT NULL,
                        description       text         NOT NULL,
                        category          varchar(20)  NOT NULL,
                        language          varchar(30)  NOT NULL,
                        duration_minutes  int          NOT NULL,
                        status            varchar(20)  NOT NULL DEFAULT 'DRAFT',
                        created_at        timestamptz  NOT NULL DEFAULT now(),
                        updated_at        timestamptz  NOT NULL DEFAULT now(),
                        CONSTRAINT ck_events_category  CHECK (category IN ('MOVIE', 'CONCERT', 'COMEDY', 'THEATRE', 'SPORTS', 'WORKSHOP')),
                        CONSTRAINT ck_events_status    CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED')),
                        CONSTRAINT ck_events_duration  CHECK (duration_minutes BETWEEN 1 AND 1440)
);
CREATE INDEX ix_events_organizer ON events (organizer_id);

CREATE TABLE shows (
                       id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       event_id    bigint      NOT NULL CONSTRAINT fk_shows_event REFERENCES events (id),
                       venue_id    bigint      NOT NULL CONSTRAINT fk_shows_venue REFERENCES venues (id),
                       starts_at   timestamptz NOT NULL,
                       status      varchar(20) NOT NULL DEFAULT 'SCHEDULED',
                       created_at  timestamptz NOT NULL DEFAULT now(),
                       updated_at  timestamptz NOT NULL DEFAULT now(),
                       CONSTRAINT uq_shows_venue_start UNIQUE (venue_id, starts_at),
                       CONSTRAINT ck_shows_status      CHECK (status IN ('SCHEDULED', 'CANCELLED'))
);
CREATE INDEX ix_shows_event ON shows (event_id);

-- One row per seat per show: price, live status for the seat map, optimistic-lock version.
CREATE TABLE show_seats (
                            id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            show_id      bigint      NOT NULL CONSTRAINT fk_show_seats_show REFERENCES shows (id),
                            seat_id      bigint      NOT NULL CONSTRAINT fk_show_seats_seat REFERENCES seats (id),
                            price_paise  bigint      NOT NULL,
                            status       varchar(20) NOT NULL DEFAULT 'AVAILABLE',
                            version      bigint      NOT NULL DEFAULT 0,
                            CONSTRAINT uq_show_seats_show_seat UNIQUE (show_id, seat_id),
                            CONSTRAINT ck_show_seats_price     CHECK (price_paise > 0),
                            CONSTRAINT ck_show_seats_status    CHECK (status IN ('AVAILABLE', 'HELD', 'BOOKED'))
);

-- =========================== booking ===========================
CREATE TABLE bookings (
                          id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          public_id     uuid        NOT NULL DEFAULT gen_random_uuid(),
                          user_id       bigint      NOT NULL CONSTRAINT fk_bookings_user REFERENCES users (id),
                          show_id       bigint      NOT NULL CONSTRAINT fk_bookings_show REFERENCES shows (id),
                          hold_id       uuid        NOT NULL,
                          status        varchar(20) NOT NULL DEFAULT 'HELD',
                          total_paise   bigint      NOT NULL,
                          currency      char(3)     NOT NULL DEFAULT 'INR',
                          expires_at    timestamptz NOT NULL,
                          confirmed_at  timestamptz,
                          cancelled_at  timestamptz,
                          version       bigint      NOT NULL DEFAULT 0,
                          created_at    timestamptz NOT NULL DEFAULT now(),
                          updated_at    timestamptz NOT NULL DEFAULT now(),
                          CONSTRAINT uq_bookings_public_id  UNIQUE (public_id),
                          CONSTRAINT uq_bookings_hold_id    UNIQUE (hold_id),
                          CONSTRAINT ck_bookings_status     CHECK (status IN ('HELD', 'PAYMENT_PENDING', 'CONFIRMED',
                                                                              'EXPIRED', 'CANCELLED', 'REFUNDED')),
                          CONSTRAINT ck_bookings_total      CHECK (total_paise >= 0),
                          CONSTRAINT ck_bookings_confirmed  CHECK (status <> 'CONFIRMED' OR confirmed_at IS NOT NULL)
);
CREATE INDEX ix_bookings_user ON bookings (user_id);
CREATE INDEX ix_bookings_show ON bookings (show_id);

CREATE TABLE booking_seats (
                               id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               booking_id   bigint  NOT NULL CONSTRAINT fk_booking_seats_booking REFERENCES bookings (id),
                               show_id      bigint  NOT NULL,
                               seat_id      bigint  NOT NULL,
                               price_paise  bigint  NOT NULL,
                               active       boolean NOT NULL DEFAULT true,
    -- the seat must exist for that show
                               CONSTRAINT fk_booking_seats_show_seat FOREIGN KEY (show_id, seat_id)
                                   REFERENCES show_seats (show_id, seat_id),
                               CONSTRAINT ck_booking_seats_price CHECK (price_paise > 0)
);
-- THE OVERSELL GUARD: at most one live claim per seat per show, even if Redis or app code fails.
-- Rows are deactivated (not deleted) on EXPIRED/CANCELLED/REFUNDED, so seats can be re-sold
-- and history is kept.
CREATE UNIQUE INDEX ux_booking_seats_live_seat ON booking_seats (show_id, seat_id) WHERE active;
CREATE INDEX ix_booking_seats_booking ON booking_seats (booking_id);